class TestRevisionTracking:
    def test_revised_scenes_detected(self, feature):
        assert any(s.revised for s in feature.scenes)

    def test_revision_marks_resolve_to_named_sets(self, feature):
        """RevisionID 2 must report as "Pink", not as a bare integer."""
        marked = [
            m
            for s in feature.scenes
            for e in s.elements
            for m in e.revision_marks
        ]
        assert marked
        assert any(m.name for m in marked)

    def test_unrevised_runs_do_not_mark(self, feature):
        """RevisionID="0" is the default and means unrevised."""
        clean = [s for s in feature.scenes if not s.revised]
        assert clean
        for scene in clean:
            assert all(not e.revision_marks for e in scene.elements)

    def test_split_runs_are_reassembled(self):
        """A paragraph split across runs is one element, marked if any run is."""
        xml = """<?xml version="1.0" encoding="UTF-8"?>
<FinalDraft DocumentType="Script" Version="5">
  <Content>
    <Paragraph Number="1" Type="Scene Heading">
      <Text RevisionID="0">INT. KITCHEN - DAY</Text>
    </Paragraph>
    <Paragraph Type="Action">
      <Text RevisionID="0">She sets the envelope down </Text>
      <Text RevisionID="2">and slides it across the table.</Text>
    </Paragraph>
  </Content>
  <Revisions><Revision ID="2" Name="Pink" Color="#FF00FF"/></Revisions>
</FinalDraft>"""
        sp = parse_fdx_string(xml)
        action = sp.scenes[0].elements[0]
        assert action.text == "She sets the envelope down and slides it across the table."
        assert action.revised
        assert action.revision_marks[0].name == "Pink"


