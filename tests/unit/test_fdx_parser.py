class TestSpeakerResolution:
    def test_dialogue_carries_its_speaker(self, small):
        dialogue = [
            e for s in small.scenes for e in s.elements if e.type is ElementType.DIALOGUE
        ]
        assert dialogue
        assert all(e.speaker for e in dialogue)

    def test_contd_resolves_to_base_character(self, small):
        """MARY (CONT'D) speaking is MARY speaking."""
        speakers = {
            e.speaker for s in small.scenes for e in s.elements if e.speaker
        }
        assert all("CONT" not in (sp or "") for sp in speakers)

    def test_action_clears_the_speaker(self):
        """Dialogue after an action line must not inherit a stale speaker."""
        xml = """<?xml version="1.0" encoding="UTF-8"?>
<FinalDraft DocumentType="Script" Version="5">
  <Content>
    <Paragraph Number="1" Type="Scene Heading"><Text>INT. KITCHEN - DAY</Text></Paragraph>
    <Paragraph Type="Character"><Text>MAE</Text></Paragraph>
    <Paragraph Type="Dialogue"><Text>Hello.</Text></Paragraph>
    <Paragraph Type="Action"><Text>She leaves.</Text></Paragraph>
  </Content>
</FinalDraft>"""
        sp = parse_fdx_string(xml)
        action = next(e for e in sp.scenes[0].elements if e.type is ElementType.ACTION)
        assert action.speaker is None


