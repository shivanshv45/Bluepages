class TestErrorHandling:
    def test_missing_file(self, tmp_path):
        with pytest.raises(FdxParseError, match="not found"):
            parse_fdx(tmp_path / "nope.fdx")

    def test_wrong_root_element(self, tmp_path):
        p = tmp_path / "bad.fdx"
        p.write_text("<?xml version='1.0'?><NotFinalDraft/>", encoding="utf-8")
        with pytest.raises(FdxParseError, match="expected <FinalDraft>"):
            parse_fdx(p)

    def test_no_content_section(self, tmp_path):
        p = tmp_path / "empty.fdx"
        p.write_text(
            "<?xml version='1.0'?><FinalDraft DocumentType='Script'/>", encoding="utf-8"
        )
        with pytest.raises(FdxParseError, match="no <Content>"):
            parse_fdx(p)

    def test_unsupported_extension(self, tmp_path):
        p = tmp_path / "script.docx"
        p.write_text("x", encoding="utf-8")
        with pytest.raises(UnsupportedFormatError):
            parse_script(p)

    def test_pdf_routes_to_tier_2(self, tmp_path):
        """PDFs now reach the tier 2 parser, which reports its own errors.

        A truncated PDF is a PDF problem, not an unsupported format.
        """
        from bluepages.parse import PdfParseError

        p = tmp_path / "script.pdf"
        p.write_bytes(b"%PDF-1.4")
        with pytest.raises(PdfParseError):
            parse_script(p)

    def test_external_entities_are_not_resolved(self, tmp_path):
        """A script arriving from outside the production must not read our disk."""
        secret = tmp_path / "secret.txt"
        secret.write_text("TOPSECRET", encoding="utf-8")
        p = tmp_path / "xxe.fdx"
        p.write_text(
            f"""<?xml version="1.0"?>
<!DOCTYPE FinalDraft [<!ENTITY xxe SYSTEM "file://{secret.as_posix()}">]>
<FinalDraft DocumentType="Script">
  <Content>
    <Paragraph Number="1" Type="Scene Heading"><Text>INT. A - DAY</Text></Paragraph>
    <Paragraph Type="Action"><Text>&xxe;</Text></Paragraph>
  </Content>
</FinalDraft>""",
            encoding="utf-8",
        )
        sp = parse_fdx(p)
        text = " ".join(e.text for s in sp.scenes for e in s.elements)
        assert "TOPSECRET" not in text


class TestProgressEvents:
    """Layer 3.6: events are emitted while working, not after."""

    def test_scene_events_emitted(self, tmp_path):
        stream = CollectingStream()
        sp = parse_fdx(FIXTURES / "small-draft-1.fdx", stream=stream)
        assert stream.count(EventKind.SCENE_PARSED) == sp.scene_count

    def test_lifecycle_events(self):
        stream = CollectingStream()
        parse_fdx(FIXTURES / "small-draft-1.fdx", stream=stream)
        assert stream.count(EventKind.PARSE_STARTED) == 1
        assert stream.count(EventKind.PARSE_FINISHED) == 1

    def test_events_carry_structured_data(self):
        """The UI consumes fields, not prose."""
        stream = CollectingStream()
        parse_fdx(FIXTURES / "small-draft-1.fdx", stream=stream)
        event = stream.of_kind(EventKind.SCENE_PARSED)[0]
        assert "scene_number" in event.data
        assert "heading" in event.data


class TestRoundTrip:
    def test_model_survives_json(self, small):
        """Layer 4 persists this and Layer 7 ships it over the wire."""
        from bluepages.model import Screenplay

        restored = Screenplay.model_validate_json(small.model_dump_json())
        assert restored.scene_count == small.scene_count
        assert [str(s.number) for s in restored.scenes] == [
            str(s.number) for s in small.scenes
        ]
