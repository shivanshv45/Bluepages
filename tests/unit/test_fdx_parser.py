"""Tests for the `.fdx` parser (Layer 1.1).

Two kinds of fixture are used deliberately:

- `sample-0*.fdx` are real Final Draft output, downloaded unmodified. They prove
  the parser handles files Final Draft actually writes, including the paragraphs
  outside `<Content>` that a naive XPath would ingest as screenplay.
- `feature-draft-1.fdx` and `small-draft-1.fdx` are generated by
  `scripts/make_fixture.py` with production structure the public samples lack:
  scene numbers, `34A` inserts, `OMITTED` scenes and revision marks.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from bluepages.events import CollectingStream, EventKind
from bluepages.model import ElementType, InteriorExterior, TimeOfDay
from bluepages.parse import UnsupportedFormatError, parse_script
from bluepages.parse.fdx import FdxParseError, parse_fdx, parse_fdx_string

FIXTURES = Path(__file__).parent.parent / "fixtures"


@pytest.fixture(scope="module")
def feature():
    return parse_fdx(FIXTURES / "feature-draft-1.fdx")


@pytest.fixture(scope="module")
def small():
    return parse_fdx(FIXTURES / "small-draft-1.fdx")


class TestRealFinalDraftFiles:
    """Against unmodified Final Draft output."""

    @pytest.mark.parametrize("name", ["sample-01", "sample-02", "sample-03"])
    def test_parses_without_error(self, name):
        sp = parse_fdx(FIXTURES / f"{name}.fdx")
        assert sp.scene_count >= 1

    def test_typed_elements_need_no_heuristics(self):
        sp = parse_fdx(FIXTURES / "sample-01.fdx")
        types = {e.type for s in sp.scenes for e in s.elements}
        assert ElementType.ACTION in types
        assert ElementType.CHARACTER in types
        assert ElementType.DIALOGUE in types
        assert ElementType.PARENTHETICAL in types

    def test_nine_revision_sets_are_read(self):
        """Blue, Pink, Yellow, Green... the paper protocol this automates."""
        sp = parse_fdx(FIXTURES / "sample-01.fdx")
        assert len(sp.revisions) == 9
        assert sp.revisions[1].name == "Blue"
        assert sp.revisions[2].name == "Pink"

    def test_unnumbered_draft_warns_about_alignment(self):
        """A draft with no scene numbers degrades alignment. Say so loudly."""
        stream = CollectingStream()
        sp = parse_fdx(FIXTURES / "sample-02.fdx", stream=stream)
        assert not sp.has_scene_numbers
        warnings = stream.of_kind(EventKind.PARSE_WARNING)
        assert any("alignment" in w.message for w in warnings)


